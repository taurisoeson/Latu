// Embeds src/latu.html into lib/latu-html.ts so the server route can return it.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../src/latu.html', import.meta.url), 'utf8');
writeFileSync(new URL('../lib/latu-html.ts', import.meta.url), '// generated by scripts/embed.mjs, do not edit\nconst html: string = ' + JSON.stringify(html) + ';\nexport default html;\n');
console.log('embedded latu.html', html.length);
